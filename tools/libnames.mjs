// Writes src/libnames.gen.ts: the public module and function names of the bundled BOSL2 and the
// file to include for each, so a forgotten include can be named in the code's problem list
// (src/diagnose.ts), and the modules' parameter names, so a failed check or an unknown argument in
// a library call can list them. Run again after updating vendor/libraries: node tools/libnames.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const dir = `${root}vendor/libraries/BOSL2`;
const read = f => readFileSync(`${dir}/${f}`, 'utf8');
const std = new Set([...read('std.scad').matchAll(/^\s*include\s*<([^>]+)>/gm)].map(m => m[1]));
const byFile = new Map(); // include file → names
const seen = new Set();
const params = new Map(); // module → its parameter names

/** The names in a module's parameter list (the text after its opening bracket), defaults left out. */
function paramNames(src, from) {
  let depth = 1, i = from, cur = '';
  const names = [];
  for (; i < src.length && depth; i++) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') {
      i = src.indexOf('\n', i);
      if (i < 0) break;
      continue;
    }
    if ('([{'.includes(c)) depth++;
    if (')]}'.includes(c)) depth--;
    if (c === ',' && depth === 1) [names[names.length], cur] = [cur, ''];
    else if (depth) cur += c;
  }
  names.push(cur);
  return names.map(n => n.split('=')[0].trim()).filter(n => /^\$?\w+$/.test(n)).join(' ');
}
/** The parameters of the modules in a file whose names are public (in `names`), first definition first. */
function addParams(src, names) {
  for (const m of src.matchAll(/^\s*module\s+([A-Za-z][A-Za-z0-9_]*)\s*\(/gm))
    if (names.has(m[1]) && !params.has(m[1])) params.set(m[1], paramNames(src, m.index + m[0].length));
}
// std.scad's files first, so a name in both counts as std.
const files = readdirSync(dir).filter(f => f.endsWith('.scad')).sort((a, b) => Number(std.has(b)) - Number(std.has(a)) || a.localeCompare(b));
for (const f of files) {
  if (f === 'std.scad') continue;
  const inc = std.has(f) ? 'std.scad' : f;
  for (const m of read(f).matchAll(/^\s*(?:module|function)\s+([A-Za-z][A-Za-z0-9_]*)\s*\(/gm)) {
    if (seen.has(m[1])) continue;
    seen.add(m[1]);
    if (!byFile.has(inc)) byFile.set(inc, []);
    byFile.get(inc).push(m[1]);
  }
  addParams(read(f), seen);
}
const entries = [...byFile].map(([f, names]) => `  '${f}': '${names.sort().join(' ')}',`);

// MCAD: one file per subject, used with use <MCAD/file.scad>. Names BOSL2 also has are left to BOSL2.
const mdir = `${root}vendor/libraries/MCAD`;
const mcad = new Map();
for (const f of [...readdirSync(mdir).filter(f => f.endsWith('.scad')), ...readdirSync(`${mdir}/bitmap`).map(f => `bitmap/${f}`)].sort()) {
  const names = [...new Set([...readFileSync(`${mdir}/${f}`, 'utf8').matchAll(/^\s*(?:module|function)\s+([A-Za-z][A-Za-z0-9_]*)\s*\(/gm)].map(m => m[1]))].filter(n => !seen.has(n));
  if (names.length) mcad.set(f, names.sort());
}
// involute_gears first: its gear() is the one AI code means (as in src/diagnose.ts).
for (const [f, names] of [...mcad].sort(([a], [b]) => Number(b === 'involute_gears.scad') - Number(a === 'involute_gears.scad')))
  addParams(readFileSync(`${mdir}/${f}`, 'utf8'), new Set(names));
const mentries = [...mcad].map(([f, names]) => `  '${f}': '${names.join(' ')}',`);

writeFileSync(`${root}src/libnames.gen.ts`, `// Generated by tools/libnames.mjs from vendor/libraries/BOSL2 and MCAD – do not edit.
// The libraries' public module and function names per file to include (for BOSL2, std.scad covers
// most), and the modules' parameter names.

export const BOSL2_NAMES: Record<string, string> = {
${entries.join('\n')}
};

export const MCAD_NAMES: Record<string, string> = {
${mentries.join('\n')}
};

export const LIB_PARAMS: Record<string, string> = {
${[...params].sort(([a], [b]) => a.localeCompare(b)).map(([n, p]) => `  ${n}: '${p}',`).join('\n')}
};
`);
console.log(`BOSL2: ${seen.size} names in ${byFile.size} include files; MCAD: ${[...mcad.values()].flat().length} names in ${mcad.size} files; parameters of ${params.size} modules`);
